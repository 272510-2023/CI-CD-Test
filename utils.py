"""Moduł zawierający podstawowe operacje matematyczne:
dodawanie, odejmowanie, mnożenie i dzielenie.
"""


def add(a, b):
    """Zwraca sumę a i b."""
    return a + b


def subtract(a, b):
    """Zwraca różnicę a - b."""
    return a - b


def multiply(a, b):
    """Zwraca iloczyn a i b."""
    return a * b


def divide(a, b):
    """Zwraca iloraz a / b. Zakłada, że b != 0."""
    return a / b
